export function othersSum(a) {
  return ((a && a.others) || []).reduce((s, o) => s + (+o.amt || 0), 0);
}

// 六项明细之和（合计字段本身不入和）：增值税+附加税+个税+企税预缴+印花税+其他税种
export function partsSum(a) {
  return ['vat', 'sur', 'it', 'cit', 'stamp'].reduce((s, k) => s + (+((a || {})[k]) || 0), 0) + othersSum(a);
}